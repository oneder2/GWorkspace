import assert from 'node:assert/strict'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const directory = mkdtempSync(join(tmpdir(), 'gworkspace-artifacts-'))
process.env.DATABASE_PATH = join(directory, 'check.db')
process.env.AI_API_KEY = ''
const { getDatabase, closeDatabase } = await import('../src/config/database.js')
try {
  const { runMigrations } = await import('../src/config/migrations.js')
  const { Project } = await import('../src/models/Project.js')
  const { Blog } = await import('../src/models/Blog.js')
  const { DailyCapsule } = await import('../src/models/DailyCapsule.js')
  const { WorldExhibit } = await import('../src/models/WorldExhibit.js')
  const { getArtifact, syncArtifact, backfillArtifacts } = await import('../src/services/gellariaArtifacts.js')
  const { readingStage } = await import('../src/services/artifactDesign.js')
  const { buildPublicWorld } = await import('../src/services/publicWorld.js')
  runMigrations({ logger: null })
  runMigrations({ logger: null })
  const db = getDatabase()
  const project = Project.create({ slug: 'cite-test', title: { zh: '学术引用检索台' }, summary: { zh: '基于文献研究与检索的引用工具。' }, technologies: ['AI'], url: 'https://example.com/cite', status: 'published', surfaces: ['gellaria'] })
  const original = getArtifact('project', project.id)
  assert.equal(original.spec.form, 'research-desk')
  assert.ok(original.spec.evidence.includes('引用'))
  assert.equal(original.spec.design.tier, 'kinetic')
  assert.equal(syncArtifact('project', project.id).revision, 1)
  Project.update(project.id, { slug: 'new-slug', summary: { zh: '文献研究、引用检索与证据校验。' } })
  const revised = getArtifact('project', project.id)
  assert.equal(revised.id, original.id)
  assert.equal(revised.spec.seed, original.spec.seed)
  assert.equal(revised.revision, 2)
  Project.update(project.id, { surfaces: ['gellaria', 'resume_web'] })
  assert.equal(getArtifact('project', project.id).spec.design.tier, 'resume')
  assert.equal(getArtifact('project', project.id).id, original.id)
  assert.equal(db.prepare('SELECT reason FROM gellaria_artifact_events WHERE artifact_id = ? ORDER BY revision DESC LIMIT 1').get(original.id).reason, 'tier')
  const draft = Blog.create({ slug: 'draft', title: '未发布', genre: 'Notes', excerpt: '', content: '未发布的内容', status: 'draft' })
  assert.equal(getArtifact('blog', draft.id), null)
  Blog.update(draft.id, { title: '旅行与故事', content: '旅途中的回忆与日记。', status: 'published' })
  assert.equal(getArtifact('blog', draft.id).spec.form, 'travel-lantern')
  const blog = Blog.create({ slug: 'design', title: '算法与架构', genre: 'Engineering', excerpt: '', content: '算法、编程与工程系统的结构。', status: 'published' })
  assert.equal(getArtifact('blog', blog.id).spec.form, 'logic-engine')
  assert.equal(getArtifact('blog', blog.id).spec.design.level, 0)
  const blogArtifactId = getArtifact('blog', blog.id).id
  for (const [views, level] of [[0, 0], [1, 1], [9, 1], [10, 2], [49, 2], [50, 3], [199, 3], [200, 4], [1999, 4], [2000, 5], [19999, 5], [20000, 6], [200000, 7]]) {
    assert.equal(readingStage(views).level, level)
  }
  for (const threshold of [1, 10, 50, 200, 2000, 20000]) {
    db.prepare('UPDATE blogs SET views = ? WHERE id = ?').run(threshold - 1, blog.id)
    const before = getArtifact('blog', blog.id)
    assert.equal(Blog.incrementViews(blog.id).views, threshold)
    const after = getArtifact('blog', blog.id)
    assert.equal(after.revision, before.revision + 1)
    assert.equal(after.id, blogArtifactId)
    assert.equal(after.spec.design.threshold, threshold)
    assert.ok(after.spec.design.segments > before.spec.design.segments)
    Blog.incrementViews(blog.id)
    assert.equal(getArtifact('blog', blog.id).revision, after.revision, 'No rebuild inside a reading tier')
  }
  const lastLevel = getArtifact('blog', blog.id).spec.design.level
  db.prepare('UPDATE blogs SET views = 0 WHERE id = ?').run(blog.id)
  syncArtifact('blog', blog.id)
  assert.equal(getArtifact('blog', blog.id).spec.design.level, lastLevel, 'Analytics corrections do not destroy model detail')
  const events = db.prepare('SELECT * FROM gellaria_artifact_events WHERE artifact_id = ? ORDER BY revision').all(blogArtifactId)
  assert.equal(events.filter(event => event.reason === 'reading-milestone').length, 6)
  assert.ok(events.every(event => JSON.parse(event.spec).design))
  // Failure to persist the model rolls back the view increment as well.
  db.prepare('UPDATE blogs SET views = 199999 WHERE id = ?').run(blog.id)
  db.exec("CREATE TRIGGER reject_artifact_event BEFORE INSERT ON gellaria_artifact_events BEGIN SELECT RAISE(ABORT, 'simulated model failure'); END")
  assert.throws(() => Blog.incrementViews(blog.id), /simulated model failure/)
  assert.equal(Blog.getById(blog.id).views, 199999)
  assert.equal(getArtifact('blog', blog.id).spec.design.level, lastLevel)
  db.exec('DROP TRIGGER reject_artifact_event')
  const capsule = DailyCapsule.upsert({ capsule_date: '2099-01-01', source_text: '一个值得记录的句子', greeting: '今日赠语', thesis: '把思考留在纸上。', boundary: '', takeaway: '' })
  assert.equal(getArtifact('capsule', capsule.id).spec.form, 'daily-leaf')
  const placement = WorldExhibit.create({ regionId: 'observatory', sourceType: 'external', sourceKey: 'external-note', title: { zh: '设计札记' }, summary: { zh: '有关设计的记录。' } })
  assert.ok(getArtifact('placement', placement.id))
  const results = backfillArtifacts()
  assert.deepEqual(backfillArtifacts(), results)
  const beforeRead = db.prepare('SELECT total_changes() AS count').get().count
  const world = buildPublicWorld()
  for (const region of world.regions.filter(region => region.id !== 'memory-grove')) {
    for (const exhibit of region.exhibits) {
      assert.ok(exhibit.artifactId?.startsWith('artifact:'))
      assert.equal(exhibit.artifactSpec.version, 2)
      assert.ok(exhibit.artifactRevision > 0)
    }
  }
  assert.equal(db.prepare('SELECT total_changes() AS count').get().count, beforeRead, 'Public reads must not generate or write models')
  const { default: express } = await import('express')
  const { default: publicRoutes } = await import('../src/routes/publicContent.js')
  const app = express()
  const { default: blogRoutes } = await import('../src/routes/blog.js')
  app.use('/api/public', publicRoutes)
  app.use('/api/blogs', blogRoutes)
  const server = app.listen(0, '127.0.0.1')
  await new Promise(resolve => server.once('listening', resolve))
  try {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api/public/world?locale=en`)
    assert.equal(response.status, 200)
    assert.match(response.headers.get('cache-control'), /max-age=30/)
    const payload = await response.json()
    assert.equal(payload.locale, 'en')
    assert.equal(payload.regions[1].exhibits[0].artifactSpec.form, 'daily-leaf')
    assert.ok(payload.regions[0].exhibits.every(exhibit => exhibit.artifactId))
    const concurrent = Blog.create({ slug: 'concurrent-views', title: '逻辑复用与 Composition API', genre: 'Code', excerpt: '', content: 'Composition API 的组件组合与逻辑复用。', status: 'published' })
    db.prepare('UPDATE blogs SET views = 9 WHERE id = ?').run(concurrent.id)
    syncArtifact('blog', concurrent.id)
    const beforeRevision = getArtifact('blog', concurrent.id).revision
    const requests = await Promise.all(Array.from({ length: 12 }, (_, i) => fetch(`http://127.0.0.1:${server.address().port}/api/blogs/${concurrent.id}/views`, { method: 'POST', headers: { 'User-Agent': `artifact-test-reader-${i}` } })))
    assert.ok(requests.every(response => response.status === 200))
    assert.equal(Blog.getById(concurrent.id).views, 21)
    assert.equal(getArtifact('blog', concurrent.id).revision, beforeRevision + 1)
    assert.equal(getArtifact('blog', concurrent.id).spec.design.level, 2)
    Blog.delete(concurrent.id)
  } finally { await new Promise(resolve => server.close(resolve)) }
  Project.update(project.id, { surfaces: ['resume_pdf'] })
  Blog.update(draft.id, { status: 'draft' })
  DailyCapsule.upsert({ capsule_date: '2099-01-01', status: 'archived', source_text: 'private', greeting: 'private', thesis: 'private', boundary: '', takeaway: '' })
  const filtered = buildPublicWorld().regions.flatMap(region => region.exhibits)
  assert.ok(!filtered.some(exhibit => exhibit.artifactId === revised.id))
  assert.ok(!filtered.some(exhibit => exhibit.id === 'blog:draft'))
  assert.ok(!filtered.some(exhibit => exhibit.id.startsWith('daily-capsule:')))
  assert.throws(() => db.prepare('INSERT INTO gellaria_artifacts (id, project_id, blog_id, source_hash, spec, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?)').run('invalid', project.id, blog.id, 'x', '{}', 'now', 'now'))
  Blog.delete(blog.id)
  assert.equal(getArtifact('blog', blog.id), null)
  assert.equal(db.prepare('SELECT count(*) AS count FROM gellaria_artifact_events WHERE artifact_id = ?').get(blogArtifactId).count, 0)
  Project.delete(project.id)
  assert.equal(getArtifact('project', project.id), null)
  WorldExhibit.delete(placement.id)
  assert.equal(getArtifact('placement', placement.id), null)
  assert.equal(db.pragma('foreign_key_check').length, 0)
  console.log(`Artifact checks passed: binding, semantic forms, revisions, slug rename, publication filtering, read-only API, cascade cleanup, idempotent backfill (${results.length} sources).`)
} finally {
  closeDatabase()
  rmSync(directory, { recursive: true, force: true })
}
